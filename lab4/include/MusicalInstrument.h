#ifndef MUSICAL_INSTRUMENT_H
#define MUSICAL_INSTRUMENT_H

#include <map>
#include <string>

/**
 * @brief Абстрактный базовый класс для всех музыкальных инструментов.
 *
 * Класс хранит общее для инструментов название и предоставляет
 * интерфейс для воспроизведения звука, настройки и определения типа.
 * Также он ведёт общую статистику: количество созданных объектов
 * и количество вызовов метода play() для каждого типа инструмента.
 *
 * От этого класса наследуются промежуточные классы струнных
 * и духовых инструментов, а от них — конкретные инструменты.
 */
class MusicalInstrument {
public:
    /**
     * @brief Создаёт музыкальный инструмент с заданным названием.
     * @param name Название инструмента.
     */
    explicit MusicalInstrument(const std::string& name);

    /**
     * @brief Создаёт копию базовой части другого инструмента.
     * @param other Объект, из которого копируются данные.
     *
     * При копировании создаётся новый объект, поэтому общий счётчик
     * существующих инструментов увеличивается.
     */
    MusicalInstrument(const MusicalInstrument& other);

    /**
     * @brief Копирует базовую часть другого инструмента.
     * @param other Объект-источник.
     * @return Ссылка на текущий объект.
     *
     * При присваивании количество объектов не меняется:
     * новый объект не создаётся и существующий не уничтожается.
     */
    MusicalInstrument& operator=(const MusicalInstrument& other);

    /**
     * @brief Уничтожает объект музыкального инструмента.
     *
     * Виртуальный деструктор нужен для корректного удаления
     * производных объектов через указатель на базовый класс.
     */
    virtual ~MusicalInstrument();

    /**
     * @brief Воспроизводит звук инструмента.
     *
     * Чисто виртуальная функция. Каждый конкретный инструмент
     * должен предоставить собственную реализацию.
     */
    virtual void play() = 0;

    /**
     * @brief Выполняет стандартную настройку инструмента.
     *
     * Производные классы могут переопределить этот метод,
     * если для их типа требуется особая настройка.
     */
    virtual void tune();

    /**
     * @brief Возвращает тип конкретного инструмента.
     * @return Строковое обозначение типа.
     *
     * Метод является чисто виртуальным, чтобы каждый конкретный
     * класс сам определял своё название типа.
     */
    virtual std::string getType() const = 0;

    /**
     * @brief Возвращает название инструмента.
     * @return Название, сохранённое в поле name_.
     */
    std::string getName() const;

    /**
     * @brief Возвращает число существующих объектов инструментов.
     * @return Текущее значение статического счётчика.
     */
    static int getInstrumentCount();

    /**
     * @brief Находит тип инструмента с наибольшим числом воспроизведений.
     * @return Название наиболее часто использованного типа
     *         или сообщение об отсутствии статистики.
     */
    static std::string getMostPlayedType();

    /**
     * @brief Выводит статистику воспроизведений по типам.
     */
    static void printPlayStatistics();

protected:
    std::string name_; ///< Название музыкального инструмента.

    /**
     * @brief Добавляет одно воспроизведение в общую статистику.
     * @param type Тип инструмента, который был воспроизведён.
     *
     * Метод защищённый, поэтому его вызывают реализации play()
     * в производных классах.
     */
    static void registerPlay(const std::string& type);

private:
    static int instrumentCount_; ///< Количество созданных и не уничтоженных объектов.
    static std::map<std::string, int> playCounts_; ///< Число воспроизведений каждого типа.

    /**
     * @brief Разрешает функции выводить закрытые данные объекта.
     * @param instrument Инструмент, сведения о котором выводятся.
     */
    friend void printInstrumentDetails(const MusicalInstrument& instrument);
};

/**
 * @brief Выводит название и тип музыкального инструмента.
 * @param instrument Объект, информацию о котором нужно вывести.
 *
 * Функция объявлена дружественной, поэтому имеет доступ к закрытым
 * членам класса MusicalInstrument.
 */
void printInstrumentDetails(const MusicalInstrument& instrument);

#endif
