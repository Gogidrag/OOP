/**
 * @file task2.cpp
 * @brief Задание 2: обработка динамического массива (new/delete)
 * 
 * Программа запрашивает размер массива, выделяет память через new,
 * находит первый отрицательный элемент и обрезает массив до него.
 * Демонстрирует работу с динамической памятью и защиту от
 * "болтающихся указателей" (dangling pointers).
 * 
 * @author Gogidrag Минаев Дмитрий 606-42
 * @date 2026
 * @version 1
 */

#include <iostream>
using namespace std;

/**
 * @brief Обрезает массив до первого отрицательного элемента
 * 
 * Функция ищет первый отрицательный элемент. Если находит —
 * создаёт новый массив без него, копирует туда всё до
 * отрицательного, освобождает старую память и переключает
 * указатель на новый массив.
 * 
 * @param arr   Ссылка на указатель массива (может быть переприсвоен)
 * @param size  Ссылка на размер массива (может измениться)
 * @return void
 */
void process(int*& arr, int& size) {

    //  ПОИСК первый отрицательный 
    int negIndex = -1;   // -1 = не нашли
    for (int i = 0; i < size; i++) {
        if (arr[i] < 0) {
            negIndex = i;
            break;   // как нашли — выходим из цикла
        }
    }
    if (negIndex == -1) {
        cout << "Отрицательных элементов нет\n";
        return;
    }

    // Вывод на какой позиции нашли
    cout << "Первый отрицательный на позиции " << negIndex << "\n";

    //  СОЗДАЁМ новый массив 
    int newSize = negIndex;              
    int* newArr = new int[newSize]{};    // обнуляем элементы

    for (int i = 0; i < newSize; i++) {
        newArr[i] = arr[i];
    }

    //  ОСВОБОЖДАЕМ старую память 
    delete[] arr;   // delete[] потому что массив

    //  ПЕРЕКЛЮЧАЕМ указатель на новый массив 
    arr = newArr;

    //  ОБНОВЛЯЕМ размер 
    size = newSize;
}

/**
 * @brief Главная функция программы
 * 
 * @return 0 при успешном завершении
 */
int main() {
    cout << "Задание 2\n\n";

    int N;
    cout << "Размер массива: ";
    cin >> N;

    // Выделяем память 
    int* arr = new int[N]{};   // обнуляем массив

    // Заполняем 
    cout << "Введи " << N << " чисел:\n";
    for (int i = 0; i < N; i++) {
        cin >> arr[i];
    }

    // Выводим исходный 
    cout << "\nИсходный: ";
    for (int i = 0; i < N; i++) {
        cout << arr[i] << " ";
    }
    cout << "\n";

    // Обрабатываем
    process(arr, N);

    // Выводим результат
    cout << "Результат: ";
    for (int i = 0; i < N; i++) {
        cout << arr[i] << " ";
    }
    cout << "\n";

    // Освобождаем память 
    delete[] arr;

    // Обнуляем указатель 
    arr = nullptr;

    // Проверка
    if (arr == nullptr) {
        cout << "\nУказатель обнулён — безопасно\n";
    }

    return 0;
}