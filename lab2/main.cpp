#include "Wallet.h"
#include <iostream>
#include <stdexcept>

/**
 * @brief Точка входа — тест класса Wallet
 * 
 * Проверяет все требования лабораторной работы:
 * - создание объектов тремя способами
 * - корректные операции (deposit, withdraw, transfer)
 * - некорректные операции (отрицательные суммы, превышение баланса)
 * - независимость объектов
 * - инварианты
 * - исключения в конструкторе
 * 
 * @return 0 при успешном завершении
 */
int main() {
    // Красивый заголовок теста
    std::cout << "\n╔══════════════════════════════════════╗\n";
    std::cout << "║   ТЕСТ КЛАССА WALLET (вариант 11)   ║\n";
    std::cout << "╚══════════════════════════════════════╝\n\n";


    // ЭТАП 1: СОЗДАНИЕ ОБЪЕКТОВ
   
    // Требование: 3 объекта, созданных разными конструкторами
    std::cout << "=== ЭТАП 1: СОЗДАНИЕ ОБЪЕКТОВ ===\n\n";

    // 1. Конструктор по умолчанию
    //    id=1, owner="Неизвестный", balance=0, currency=RUB
    Wallet w1;
    std::cout << "\n";

    // 2. Параметризованный конструктор
    //    задаём id=7, владельца, баланс, валюту
    Owner owner2{"Cristiano Ronaldo", "1234 567890"};
    Wallet w2(7, owner2, 5000.0, Currency::RUB);
    std::cout << "\n";

    // 3. Конструктор копирования
    //    копия w2 — все поля такие же, как у w2
    Wallet w3(w2);
    std::cout << "\n";

    // Проверяем, что все 3 объекта созданы
    std::cout << "Всего объектов: " << Wallet::getObjectCount() << "\n\n";

    // ЭТАП 2: НАЧАЛЬНОЕ СОСТОЯНИЕ
  
    // Выводим состояние всех объектов ДО операций
    std::cout << "=== ЭТАП 2: НАЧАЛЬНОЕ СОСТОЯНИЕ ===\n\n";
    
    std::cout << "Кошелёк 1:\n";
    w1.printInfo();
    
    std::cout << "\nКошелёк 2:\n";
    w2.printInfo();
    
    std::cout << "\nКошелёк 3 (копия второго):\n";
    w3.printInfo();
    std::cout << "\n";

    
    // ЭТАП 3: КОРРЕКТНЫЕ ОПЕРАЦИИ
   
    // Все операции правильные — должны сработать
    std::cout << "=== ЭТАП 3: КОРРЕКТНЫЕ ОПЕРАЦИИ ===\n\n";

    w1.deposit(7000);        // пополняем w1 на 7000
    w2.deposit(14000);       // пополняем w2 на 14000
    w2.withdraw(5000);       // списываем с w2 5000
    w2.transfer(w1, 3000);   // переводим с w2 на w1 3000

    // Показываем, что балансы изменились правильно
    std::cout << "\nСостояние после корректных операций:\n\n";
    std::cout << "Кошелёк 1:\n";
    w1.printInfo();
    std::cout << "\nКошелёк 2:\n";
    w2.printInfo();
    std::cout << "\n";


    // ЭТАП 4: НЕКОРРЕКТНЫЕ ОПЕРАЦИИ
   
    // Все операции НЕПРАВИЛЬНЫЕ — должны отказать
    // Баланс НЕ должен измениться
    std::cout << "=== ЭТАП 4: НЕКОРРЕКТНЫЕ ОПЕРАЦИИ ===\n\n";

    // Запоминаем баланс ДО ошибок
    double before = w1.getBalance();
    std::cout << "Баланс w1 до ошибок: " << before << "\n\n";

    // Попытка пополнить отрицательной суммой
    w1.deposit(-500);

    // Попытка списать отрицательную сумму
    w1.withdraw(-100);

    // Попытка списать больше, чем есть
    w1.withdraw(99999);

    std::cout << "\n";

    // Блокируем кошелёк
    w1.block();

    // Попытка пополнить заблокированный
    w1.deposit(100);

    // Попытка списать с заблокированного
    w1.withdraw(50);

    // Разблокируем
    w1.unblock();

    // Проверяем, что баланс НЕ изменился
    double after = w1.getBalance();
    std::cout << "\nБаланс w1 после ошибок: " << after << "\n";
    std::cout << (before == after ? "✅ Баланс не изменился!" : "❌ Баланс изменился!") << "\n\n";

  
    // ЭТАП 5: СОСТОЯНИЕ ПОСЛЕ ОШИБОК
    
    // Показываем, что объект остался корректным
    std::cout << "=== ЭТАП 5: СОСТОЯНИЕ ПОСЛЕ ОШИБОК ===\n\n";
    std::cout << "Кошелёк 1:\n";
    w1.printInfo();
    std::cout << "\n";

   
    // ЭТАП 6: НЕЗАВИСИМОСТЬ ОБЪЕКТОВ
    
    // Меняем один объект — проверяем, что другой не изменился
    std::cout << "=== ЭТАП 6: НЕЗАВИСИМОСТЬ ОБЪЕКТОВ ===\n\n";

    // Запоминаем балансы ДО изменения
    double w1Before = w1.getBalance();
    double w3Before = w3.getBalance();

    std::cout << "До изменения:\n";
    std::cout << "  w1 баланс: " << w1Before << "\n";
    std::cout << "  w3 баланс: " << w3Before << "\n\n";

    // Меняем только w1
    w1.deposit(999);

    std::cout << "\nПосле пополнения w1 на 999:\n";
    std::cout << "  w1 баланс: " << w1.getBalance() << "\n";
    std::cout << "  w3 баланс: " << w3.getBalance() << "\n";
    
    // Проверяем, что w3 не изменился
    if (w3.getBalance() == w3Before) {
        std::cout << "✅ w3 не изменился — объекты независимы!\n\n";
    } else {
        std::cout << "❌ w3 изменился — ошибка!\n\n";
    }

    
    // ЭТАП 7: ПРОВЕРКА ИНВАРИАНТОВ

    // Проверяем, что все объекты корректны
    std::cout << "=== ЭТАП 7: ПРОВЕРКА ИНВАРИАНТОВ ===\n\n";
    std::cout << "w1 корректен: " << (w1.isValid() ? "✅ да" : "❌ нет") << "\n";
    std::cout << "w2 корректен: " << (w2.isValid() ? "✅ да" : "❌ нет") << "\n";
    std::cout << "w3 корректен: " << (w3.isValid() ? "✅ да" : "❌ нет") << "\n\n";

    
    // ЭТАП 8: ПРОВЕРКА ИСКЛЮЧЕНИЙ
    
    // Пытаемся создать "сломанные" объекты
    // Конструктор должен бросить исключение
    std::cout << "=== ЭТАП 8: ПРОВЕРКА ИСКЛЮЧЕНИЙ ===\n\n";
    
    // ID = 0 (некорректно)
    try {
        Wallet bad(0, {"Тест", "0000"}, 100, Currency::RUB);
    } catch (const std::exception& e) {
        std::cout << "✅ Поймано исключение: " << e.what() << "\n";
    }
    
    // Пустое имя владельца (некорректно)
    try {
        Wallet bad(1, {"", "0000"}, 100, Currency::RUB);
    } catch (const std::exception& e) {
        std::cout << "✅ Поймано исключение: " << e.what() << "\n";
    }
    
    // Отрицательный баланс (некорректно)
    try {
        Wallet bad(1, {"Тест", "0000"}, -100, Currency::RUB);
    } catch (const std::exception& e) {
        std::cout << "✅ Поймано исключение: " << e.what() << "\n";
    }

    
    // КОНЕЦ ТЕСТА
   
    std::cout << "\n";
    std::cout << "=== КОНЕЦ ТЕСТА ===\n";
    std::cout << "Всего объектов перед выходом: " << Wallet::getObjectCount() << "\n\n";

    // При выходе из main сработают деструкторы:
    // w3, w2, w1 — в обратном порядке создания
    return 0;
}